def clean_text(text):
    if pd.isna(text):
        return ""
    return re.sub(r"[\s·•ㆍ]+", "", str(text).strip())

def normalize_univ(univ_raw):
    cleaned = clean_text(univ_raw)
    if cleaned in UNIV_ALIAS_MAP:
        return UNIV_ALIAS_MAP[cleaned]
    if cleaned.endswith("대") and not cleaned.endswith("대학교"):
        candidate = cleaned + "학교"
        if candidate in OFFICIAL_UNIV_MAJORS:
            return candidate
    return str(univ_raw).strip()

def match_major(univ_std, major_raw, threshold=72):
    # '합격명단 게시물에서 제외', '?' 등 비학과 텍스트를 미입력으로 처리
    if pd.isna(major_raw) or str(major_raw).strip() in ("", "0", "?", "합격명단 게시물에서 제외"):
        return "", "미입력", 0

    major_str = str(major_raw).strip()
    major_clean = clean_text(major_str)

    # 캠퍼스 자동 교정 1: 중앙대(서울) -> 다빈치
    if univ_std == "중앙대학교(서울)" and major_clean in ("디자인학부(패션)", "예술공학부", "시스템생명공학과", "첨단소재공학과"):
        return major_str, "캠퍼스_다빈치교정", 100

    # 캠퍼스 자동 교정 2: 단국대(죽전) -> 천안
    if univ_std == "단국대학교(죽전)":
        cheonan_cleaned = {clean_text(c): c for c in OFFICIAL_UNIV_MAJORS["단국대학교(천안)"]}
        if major_clean in cheonan_cleaned or any(k in major_clean for k in ["의생명", "생명자원", "보건행정", "임상병리", "물리치료", "치위생", "간호", "의학", "치의학", "약학", "공공정책", "해병대", "식품자원", "뉴뮤직", "공예"]):
            return major_str, "캠퍼스_단국천안교정", 100

    # 캠퍼스 자동 교정 3: 한국외대(서울) -> 글로벌 (환경학과 등 글로벌 전용 학과)
    if univ_std == "한국외국어대학교(서울)" and major_clean in ("환경학과", "전자물리학과", "생명공학과", "통계학과", "수학과"):
        return major_str, "캠퍼스_외대글로벌교정", 100

    # 1) 특수 매핑 사전 확인
    if (univ_std, major_clean) in SPECIAL_MAJOR_MAP:
        return SPECIAL_MAJOR_MAP[(univ_std, major_clean)], "사전매핑(개편/통합)", 100

    # 내장 기준표에 없는 대학인 경우
    if univ_std not in OFFICIAL_UNIV_MAJORS:
        return major_str, "기준표외_대학", 0

    candidates = OFFICIAL_UNIV_MAJORS[univ_std]
    cleaned_to_official = {clean_text(c): c for c in candidates}

    # 2) 정제 후 정확 일치
    if major_clean in cleaned_to_official:
        return cleaned_to_official[major_clean], "정확일치", 100

    # 3) 접미사(학과/학부/전공) 제거 후 핵심 명칭 일치
    core_query = re.sub(r"(학과|학부|전공)$", "", major_clean)
    for c_clean, c_official in cleaned_to_official.items():
        core_cand = re.sub(r"(학과|학부|전공)$", "", c_clean)
        if core_query and core_query == core_cand:
            return c_official, "핵심명칭일치", 98

    # 4) 부분 포함 유일 매칭
    substring_matches = [
        c_official for c_clean, c_official in cleaned_to_official.items()
        if core_query and len(core_query) >= 2 and core_query in c_clean
    ]
    if len(substring_matches) == 1:
        return substring_matches[0], "부분포함_유일매칭", 92

    # 5) 유사도 기반 자동 매칭
    best_match = process.extractOne(major_str, candidates, scorer=fuzz.WRatio)
    if best_match:
        matched_name, score, _ = best_match
        if score >= threshold:
            return matched_name, "유사도_자동매칭", round(score, 1)
        else:
            return major_str, f"검토필요(후보:{matched_name})", round(score, 1)

    return major_str, "매칭실패", 0

def main():
    if STUDENT_FILE_PATH.suffix.lower() == ".csv":
        try:
            df = pd.read_csv(STUDENT_FILE_PATH, encoding="utf-8-sig")
        except UnicodeDecodeError:
            df = pd.read_csv(STUDENT_FILE_PATH, encoding="cp949")
    else:
        df = pd.read_excel(STUDENT_FILE_PATH)

    def process_row(row):
        univ_raw = row[COL_UNIV]
        major_raw = row[COL_MAJOR]

        if pd.isna(univ_raw) or str(univ_raw).strip() == "":
            return "", "", "대학_미입력", 0

        univ_std = normalize_univ(univ_raw)
        major_std, status, score = match_major(univ_std, major_raw)

        # 캠퍼스 자동 교정 후 재매칭
        if status == "캠퍼스_다빈치교정":
            univ_std = "중앙대학교(다빈치)"
            major_std, status, score = match_major(univ_std, major_raw)
            status = "사전매핑(캠퍼스교정)"
        elif status == "캠퍼스_단국천안교정":
            univ_std = "단국대학교(천안)"
            major_std, status, score = match_major(univ_std, major_raw)
            status = "사전매핑(캠퍼스교정)"
        elif status == "캠퍼스_외대글로벌교정":  # <-- 바로 이 위치입니다!
            univ_std = "한국외국어대학교(글로벌)"
            major_std, status, score = match_major(univ_std, major_raw)
            status = "사전매핑(캠퍼스교정)"

        return univ_std, major_std, status, score

    results = df.apply(process_row, axis=1)

    df[COL_UNIV] = [r[0] for r in results]
    df[COL_MAJOR] = [r[1] for r in results]
    df["매칭_상태"] = [r[2] for r in results]
    df["유사도_점수"] = [r[3] for r in results]

    OUTPUT_FILE_PATH.parent.mkdir(parents=True, exist_ok=True)
    df.to_excel(OUTPUT_FILE_PATH, index=False)

    print("=== 32개 대학/캠퍼스 학과명 자동 매핑 완료 ===")
    print(df["매칭_상태"].value_counts())
    review_cnt = df[df["매칭_상태"].str.startswith("검토필요")].shape[0]
    print(f"\n저장 경로: {OUTPUT_FILE_PATH}")
    print(f"수동 검토가 필요한 행 수: {review_cnt}건")


if __name__ == "__main__":
    main()